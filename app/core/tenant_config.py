"""Tenant folder format (tenants/<slug>/tenant.yaml + catalogue.csv) and its validation.

Generic: nothing here may mention a specific tenant.
"""

import csv
from datetime import date
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, Field, StrictInt

from app.core.settings_resolver import SettingsError, resolve, validate_setting
from app.core.verticals import ROOT, VerticalPack

TENANTS_DIR = ROOT / "tenants"

Role = Literal["customer", "location_manager", "franchisee_owner", "hq_owner"]


class BrandCfg(BaseModel):
    slug: str
    name: str


class LocationCfg(BaseModel):
    slug: str
    name: str
    brands: list[str]


class UserCfg(BaseModel):
    email: str
    name: str
    role: Role
    brands: list[str] = Field(default_factory=list)
    locations: list[str] = Field(default_factory=list)
    # Dev/demo only: overrides the tenant's demo_password for this user.
    demo_password: str | None = Field(default=None, min_length=8, max_length=72)


class SettingsCfg(BaseModel):
    org: dict[str, Any] = Field(default_factory=dict)
    brands: dict[str, dict[str, Any]] = Field(default_factory=dict)
    locations: dict[str, dict[str, Any]] = Field(default_factory=dict)


class CatalogueItemCfg(BaseModel):
    brand: str
    sku: str
    name: str
    category: str
    price_paise: StrictInt = Field(ge=0)


Range = tuple[int, int]


class ProblemCfg(BaseModel):
    """A planted problem. Filters (location, hours, weekdays_only) narrow where it applies;
    when several rules of one kind apply to an order, the highest rate wins."""

    kind: Literal["late", "missing_item", "wrong_item", "repeat_drop"]
    rate: float = Field(default=0.0, ge=0, le=1)
    location: str | None = None
    hours: Range | None = None  # local time, [start, end)
    weekdays_only: bool = False
    extra_minutes: Range | None = None  # late: minutes past the promise
    from_day: int | None = None  # repeat_drop: first affected day (0-based)
    factor: float = Field(default=0.0, ge=0, le=1)  # repeat_drop: share of orders lost to churn


class MessyCfg(BaseModel):
    duplicate_phone_rate: float = Field(default=0.0, ge=0, le=1)
    orders_outside_window: int = Field(default=0, ge=0)
    multi_location_customer_rate: float = Field(default=0.0, ge=0, le=1)
    opted_out_rate: float = Field(default=0.0, ge=0, le=1)


class SimulationCfg(BaseModel):
    """History generated by simulator/ (PROJECT.md section 14). Same seed -> same data."""

    end_date: date  # fixed, so the data never depends on today's date
    days: int = Field(gt=0)
    customers: int = Field(gt=0)
    orders: int = Field(gt=0)
    past_tickets: int = Field(ge=0)
    hours: Range  # ordering window, local time [start, end)
    items_per_order: Range = (1, 3)
    promise_minutes: Range
    delay_minutes: Range  # normal deviation from the promise (negative = early)
    source_weights: dict[str, float] = Field(default_factory=dict)
    location_weights: dict[str, float] = Field(default_factory=dict)
    problems: list[ProblemCfg] = Field(default_factory=list)
    messy: MessyCfg = Field(default_factory=MessyCfg)
    ticket_categories: dict[str, str] = Field(default_factory=dict)  # problem kind -> category
    default_ticket_category: str = "status_question"


class TenantConfig(BaseModel):
    slug: str
    name: str
    vertical_pack: str
    brands: list[BrandCfg]
    locations: list[LocationCfg]
    feature_flags: dict[str, bool] = Field(default_factory=dict)
    settings: SettingsCfg = Field(default_factory=SettingsCfg)
    users: list[UserCfg] = Field(default_factory=list)
    # Dev/demo only: plaintext password for the seeded users (hashed into the DB only when
    # DEMO_AUTH is on; listed by GET /auth/demo-accounts outside prod). Never real credentials.
    demo_password: str | None = Field(default=None, min_length=8, max_length=72)
    catalogue: list[CatalogueItemCfg] = Field(default_factory=list)
    simulation: SimulationCfg | None = None

    def demo_password_for(self, user: UserCfg) -> str | None:
        return user.demo_password or self.demo_password


def tenant_dirs(root: Path = TENANTS_DIR) -> list[Path]:
    return sorted(p for p in root.iterdir() if (p / "tenant.yaml").is_file())


def load_tenant(folder: Path) -> TenantConfig:
    data = yaml.safe_load((folder / "tenant.yaml").read_text(encoding="utf-8"))
    catalogue_path = folder / "catalogue.csv"
    if catalogue_path.is_file():
        with catalogue_path.open(encoding="utf-8", newline="") as f:
            # int() rejects "349.50": catalogue prices must already be integer paise.
            data["catalogue"] = [
                {**row, "price_paise": int(row["price_paise"])} for row in csv.DictReader(f)
            ]
    cfg = TenantConfig.model_validate(data)
    if cfg.slug != folder.name:
        raise ValueError(f"{folder.name}/tenant.yaml declares slug {cfg.slug!r}")
    return cfg


def validate_tenant(cfg: TenantConfig, pack: VerticalPack) -> None:
    """Cross-reference checks the schema alone can't express. Raises ValueError."""
    if cfg.vertical_pack != pack.slug:
        raise ValueError(f"tenant uses pack {cfg.vertical_pack!r}, got {pack.slug!r}")
    brands = _unique([b.slug for b in cfg.brands], "brand")
    locations = _unique([loc.slug for loc in cfg.locations], "location")
    _unique([u.email for u in cfg.users], "user email")
    _unique([i.sku for i in cfg.catalogue], "sku")

    for loc in cfg.locations:
        _known(loc.brands, brands, f"location {loc.slug} brand")
    for user in cfg.users:
        _known(user.brands, brands, f"user {user.email} brand")
        _known(user.locations, locations, f"user {user.email} location")
    _known([i.brand for i in cfg.catalogue], brands, "catalogue brand")
    _known(cfg.settings.brands, brands, "settings brand")
    _known(cfg.settings.locations, locations, "settings location")
    _known(cfg.feature_flags, set(pack.features), "feature flag")

    try:
        # Every override on its own (also brands no location carries), then every combination.
        for layer in [
            cfg.settings.org,
            *cfg.settings.brands.values(),
            *cfg.settings.locations.values(),
        ]:
            for key, value in layer.items():
                validate_setting(pack.settings, key, value)
        for loc in cfg.locations:
            for brand in loc.brands:
                resolve(
                    pack.settings,
                    cfg.settings.org,
                    cfg.settings.brands.get(brand, {}),
                    cfg.settings.locations.get(loc.slug, {}),
                )
    except SettingsError as exc:
        raise ValueError(f"settings: {exc}") from exc

    if cfg.simulation is not None:
        _validate_simulation(cfg, pack, brands, locations)


def _validate_simulation(
    cfg: TenantConfig, pack: VerticalPack, brands: set[str], locations: set[str]
) -> None:
    sim = cfg.simulation
    _known(sim.source_weights, set(pack.order_sources), "simulation source")
    _known(sim.location_weights, locations, "simulation location weight")
    _known(pack.order_sources, set(pack.fulfilment_kinds), "pack fulfilment kind for source")
    categories = set(pack.issue_categories)
    _known(sim.ticket_categories.values(), categories, "simulation ticket category")
    _known([sim.default_ticket_category], categories, "simulation default ticket category")
    with_items = {i.brand for i in cfg.catalogue}
    _known(brands, with_items, "catalogue entries for brand (every brand needs items); missing")
    for p in sim.problems:
        if p.location is not None:
            _known([p.location], locations, "simulation problem location")
        if p.kind == "late":
            if p.extra_minutes is None:
                raise ValueError("late problem needs extra_minutes")
            # Normal variance must never look like a planted late order.
            if sim.delay_minutes[1] >= p.extra_minutes[0]:
                raise ValueError("delay_minutes must stay below late extra_minutes")
        if p.kind == "repeat_drop" and (p.location is None or p.from_day is None):
            raise ValueError("repeat_drop needs location and from_day")


def _unique(values: list[str], what: str) -> set[str]:
    seen = set(values)
    if len(seen) != len(values):
        raise ValueError(f"duplicate {what}")
    return seen


def _known(values, known: set[str], what: str) -> None:
    unknown = set(values) - known
    if unknown:
        raise ValueError(f"unknown {what}: {sorted(unknown)}")
